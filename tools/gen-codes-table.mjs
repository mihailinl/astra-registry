#!/usr/bin/env node
//
// FLOW-13's reason-code table, emitted from the bot's own code tables.
//
//   node tools/gen-codes-table.mjs --out tools/codes-table.json
//   node tools/gen-codes-table.mjs --check tools/codes-table.json
//   node tools/gen-codes-table.mjs --print
//   node tools/gen-codes-table.mjs --selftest
//
// **This program does not write the token file, and that is the whole shape of
// it.** Contract FLOW-13 publishes the table *inside* SCOPE-7's
// `schema/contract-tokens-v1.json` (0.13.0's n8), so that the panel, SCOPE-1's
// comparison and the canary read one artifact at one commit. But that file is
// generated by `astra-plugins-ops` `tools/contract-tokens.mjs`, which reads the
// contract and nothing else — and the codes are not in the contract, they are
// in this repository's `bot/lib/codes.mjs` and `POLICY_CODES`. So the two
// programs meet at a file:
//
//   this  →  tools/codes-table.json  →  contract-tokens.mjs --codes  →  the token file
//
// The registry plan's B-T2.3 still says this emitter writes into the token
// file directly. It cannot: that would put two writers on one artifact, in two
// repositories, and the second one to run would silently drop the first one's
// work. The intermediate is the correction, and `tools/codes-table.json` is its
// path — chosen here because the plan names none anywhere (measured absent in
// B-T2.3's block, in RC-R2-1's, and in the ops generator). It is committed
// rather than built on demand, because `astra-plugins-ops`'s own
// `tools/check-contract.mjs` regenerates the token file from a registry
// checkout to compare it, and a checker that has to execute this repository's
// code to do that is a checker that cannot run from a clean checkout.
//
// **`codes` is not decoration, and it is the reason this file has the shape it
// has.** The ops generator's first `--codes` merge took a bare array of rows
// and asserted every row was complete. A table with one code's row deleted
// PASSED — it had to, because that program runs in another repository and
// cannot read `bot/lib/codes.mjs`, so "one entry per code the bot emits" is a
// claim only this program can make. So this program makes it: `codes` is the
// complete list of every code name its sources define, `codes_source` is the
// files it read, and the merge compares the table with that list **in both
// directions**. A deleted row is then a row missing from a population the same
// file declares, and a row nobody declares is a row naming no code.
//
// Nothing here reads a clock, a directory listing or a network: the output is
// a function of the two source modules alone.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { CODES } from "../bot/lib/codes.mjs";
import { POLICY_CODES, policyCodeDef } from "../bot/lib/policy.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The two files OPEN-OPS-8 names, and the only two this program reads. */
const SOURCES = ["bot/lib/codes.mjs", "bot/lib/policy/constants.mjs"];

/** FLOW-13's closed list. Nothing else may appear in a `fix`. */
const FIXES = ["recheck", "new_tag", "moderator", "registry", "none"];

/** The levels a code may carry (`bot/lib/codes.mjs`'s `Level`). */
const LEVELS = ["error", "review", "warn", "note", "pass", "skip"];

/** FLOW-13's six members, plus the code itself. */
const MEMBERS = ["code", "level", "stage", "fix", "panel_only", "title", "remedy"];

// The stages at which every finding is a property of bytes the build
// attestation already covers. A Recheck re-runs the same tag (FLOW-4), so at
// these stages `recheck` is never the answer — the same bytes are read again
// and reach the same verdict. This is the rule `bot/lib/codes.mjs`'s header
// states, written here as something that fails rather than something that is
// merely documented; it is the check that would have caught FLOW-13's own
// worked example going the wrong way (`B_UNBOUND` is `new_tag`, not
// `recheck`, and for exactly this reason).
const ATTESTED_STAGES = ["bundle", "manifest", "metadata", "version", "rpc-scan", "names"];

// B.7's panel-only details and the wait only the service shows. FLOW-13's
// panel-only flag exists to mark these; no code the bot emits may be one, and
// asserting that is what turns the flag from a claim into a measurement.
const PANEL_ONLY = ["B_BINDING_INVALID", "B_ACCOUNT_INELIGIBLE", "W_REGISTRY_UNACKNOWLEDGED"];

// FLOW-15: a remedy on the service path may not tell an author to comment, to
// `/recheck`, or to say anything "in the issue" — on that path there is no
// issue and there is no comment box. Applied to the codes the service turns
// into waits (FLOW-72), which is what `policyCodeDef(code, {path: "service"})`
// answers. The rest of FLOW-15's scrub is the legacy path's and is gated at
// ROLL-44 by FLOW-15's own Check line.
const CHANNEL = /\/recheck|comment|in the issue/i;

// B.7 names codes this table cannot carry yet, and the absence is recorded
// rather than left to be discovered. Their levels are declared
// (`BOUND_WORLD_CODES` in `bot/lib/policy/constants.mjs`) and their titles and
// remedies are not written anywhere in this repository — deliberately:
// reg.61a (B-T3.3b) writes those author-facing sentences once, into
// docs/POLICY.md, and a placeholder here would be a second one, and the second
// one is the one that ships. So they are owed, by name, and this program
// neither invents them nor pretends the codes do not exist.
const OWED = {
  owed_by: "reg.61a (registry plan B-T3.3b), which writes these codes' author-facing sentences into docs/POLICY.md",
  why:
    "FLOW-13 requires a title and a remedy per entry. These codes carry a level in " +
    "`bot/lib/policy/constants.mjs`'s `BOUND_WORLD_CODES` and no title and no remedy anywhere in this " +
    "repository. `policyCodeDef` synthesises `See docs/POLICY.md.` for them at emit time, which is the " +
    "right answer in a comment and the wrong one in a published table three estates compile against.",
  codes: [
    "B_UNBOUND", "B_BINDING_MALFORMED", "B_BINDING_UNUSABLE", "B_BINDING_INVALID",
    "B_ACCOUNT_INELIGIBLE", "B_OWNER_CHANGED", "B_REPOSITORY_RECYCLED",
    "R_FIRST_BINDING", "R_BINDING_CHANGED",
    "W_LEASE_EXPIRED", "W_ELIGIBILITY_UNREADABLE", "W_NOTICE_PENDING", "W_GITHUB_RATE_LIMITED",
    "W_SERVICE_UNREACHABLE", "W_MODERATION_HOLD", "W_ALERT_UNDELIVERED", "W_OPERATOR_WINDOW",
    "W_REGISTRY_UNACKNOWLEDGED",
    "M_APPROVE", "M_REJECT", "M_APPEAL",
    "A_STOP", "A_WITHDRAW", "A_BINDING_REVOKE", "A_REMOVAL_REQUEST", "A_YANK",
  ],
};

/** Floors. Below these the walk has failed, not the vocabulary shrunk. */
const CODE_FLOOR = 100;
const STAGE_FLOOR = 10;

class Problems {
  constructor() { this.list = []; }
  fail(where, what) { this.list.push(`${where}: ${what}`); }
}

/**
 * The table, and the population it is a table of.
 *
 * Rows are sorted by code so that the output is a function of the sources and
 * not of two objects' insertion orders.
 */
export function build() {
  const p = new Problems();
  const rows = [];
  const seen = new Map();

  const add = (code, def, source) => {
    const prior = seen.get(code);
    if (prior) {
      // Two tables declaring one code is allowed — `R_FIRST_LISTING` and
      // `R_IDENTITY_CHANGED` are in both — but two ANSWERS are not. The panel
      // reads one row, so the row it reads must not depend on which file the
      // emitter happened to walk second. Title and remedy are prose about two
      // different moments and are allowed to differ; `level`, `stage` and
      // `fix` are what the panel routes on and must not. On its first run this
      // check found the two duplicates carrying stage `version` in one table
      // and `policy` in the other, which had been true on `main` since the
      // policy module was split out.
      for (const k of ["level", "stage", "fix"]) {
        if (prior.def[k] !== def[k]) {
          p.fail(code, `${source} says ${k} ${JSON.stringify(def[k])} and ${prior.source} says ` +
            `${JSON.stringify(prior.def[k])}. One code, two answers, and the panel reads one row`);
        }
      }
      return;
    }
    seen.set(code, { def, source });

    for (const k of ["level", "stage", "fix", "title", "remedy"]) {
      if (typeof def[k] !== "string" || def[k].length === 0) {
        p.fail(code, `${source} gives it no ${k}. FLOW-13's table is one FULL entry per code`);
      }
    }
    if (!LEVELS.includes(def.level)) p.fail(code, `level ${JSON.stringify(def.level)} is not one of ${LEVELS.join(", ")}`);
    if (!FIXES.includes(def.fix)) {
      p.fail(code, `fix ${JSON.stringify(def.fix)} is not one of FLOW-13's closed list ${FIXES.join(", ")}`);
    }

    // The rule, as a check. See ATTESTED_STAGES above.
    if (def.level === "review" && def.fix !== "moderator") {
      p.fail(code, `is level review and fix ${JSON.stringify(def.fix)}; a review waits on a person, so it is cleared by \`moderator\``);
    }
    if (["warn", "note", "pass"].includes(def.level) && def.fix !== "none") {
      p.fail(code, `is level ${def.level} and fix ${JSON.stringify(def.fix)}; nothing is blocked, so nothing clears it`);
    }
    if (def.level === "error" && ATTESTED_STAGES.includes(def.stage) && def.fix === "recheck") {
      p.fail(code, `is an error at stage ${def.stage} with fix \`recheck\`. A Recheck re-runs the same tag ` +
        `(FLOW-4) and reads the same attested bytes, so it reaches the same verdict for ever`);
    }

    // `panel_only` is derived, not declared. Every code in these two tables is
    // one the bot emits, which is exactly what panel-only denies. A source
    // that ever declares one explicitly is honoured, and the assertion below
    // then catches it if it is one of B.7's.
    const panelOnly = def.panel_only === true;
    if (panelOnly || PANEL_ONLY.includes(code)) {
      p.fail(code, `is panel-only and is declared in ${source}. The panel-only flag marks B.7's ` +
        `panel-only details and the waits only the service shows; a bot module emitting one would ` +
        `publish what \`B_BINDING_UNUSABLE\` withholds (BOT-89)`);
    }

    // FLOW-15, on the path it binds.
    const onService = policyCodeDef(code, { path: "service" });
    if (onService && onService.level === "wait" && CHANNEL.test(def.remedy)) {
      p.fail(code, `is a wait on the service path (FLOW-72) and its remedy names a channel that path ` +
        `does not have: ${JSON.stringify(def.remedy.match(CHANNEL)[0])} (FLOW-15)`);
    }

    rows.push({
      code,
      level: def.level,
      stage: def.stage,
      fix: def.fix,
      panel_only: panelOnly,
      title: def.title,
      remedy: def.remedy.replace(/\s+/g, " ").trim(),
    });
  };

  // `POLICY_CODES` is walked first, so its title and remedy win for a code
  // declared twice. That is not a preference: `policyCodeDef()` resolves
  // `POLICY_CODES` before anything else, so this is the same answer the bot
  // itself gives when it reports one of those two codes.
  for (const [code, def] of Object.entries(POLICY_CODES)) add(code, def, "bot/lib/policy/constants.mjs");
  for (const [code, def] of Object.entries(CODES)) add(code, def, "bot/lib/codes.mjs");

  rows.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));

  if (rows.length < CODE_FLOOR) {
    p.fail("floor", `${rows.length} codes read from ${SOURCES.length} sources; the floor is ${CODE_FLOOR}. ` +
      `A vocabulary this small is a broken import, not a smaller bot`);
  }
  const stages = new Set(rows.map((r) => r.stage));
  if (stages.size < STAGE_FLOOR) {
    p.fail("floor", `${stages.size} distinct stages; the floor is ${STAGE_FLOOR}`);
  }

  if (p.list.length) {
    const e = new Error(
      `${p.list.length} problem(s) in the reason-code table, so it was NOT emitted:\n  ` + p.list.join("\n  "));
    e.problems = p.list;
    throw e;
  }

  return {
    readme: [
      "FLOW-13's reason-code table, emitted by tools/gen-codes-table.mjs from the two files in `codes_source` and from nothing else.",
      "This file is an INTERMEDIATE and not the published interface. The published one is FLOW-13's table inside SCOPE-7's `schema/contract-tokens-v1.json`, where astra-plugins-ops `tools/contract-tokens.mjs --codes <this file>` merges it (0.13.0's n8).",
      "`codes` is the complete list of every code name those sources define. It is here so the merge can compare the table with the population in BOTH directions: without it a deleted row is indistinguishable from a code that does not exist, which was watched, and passed.",
      "`codes_owed` names the B.7 codes this table cannot carry yet and who owes their title and remedy. An absent code is recorded, never silently dropped.",
    ],
    codes_source: SOURCES,
    codes: rows.map((r) => r.code),
    codes_owed: OWED,
    flow13_table: rows,
  };
}

/** Where this program may write. See canary (4) in B-T2.3. */
function refuseBadOutput(out) {
  const rel = path.relative(REPO, path.resolve(out)).split(path.sep).join("/");
  if (rel.startsWith("schema/")) {
    throw new Error(
      `refusing to write ${rel}. FLOW-13's table is published inside SCOPE-7's token file and nowhere ` +
      `else (0.13.0's n8); a second artifact under schema/ is the unpinned second copy that decision ` +
      `removed, and a twelfth file under schema/ is a contract MINOR besides (TRUST-31)`);
  }
  if (path.basename(rel) === "reason-codes-v1.json") {
    throw new Error(
      `refusing to write ${rel}. \`schema/reason-codes-v1.json\` is the file the 0.12.0 plan created and ` +
      `0.13.0 deleted (n8). Writing it under any directory recreates the two-artifact problem under a ` +
      `name that makes it look published`);
  }
}

const serialise = (doc) => JSON.stringify(doc, null, 2) + "\n";

// ── the selftest: the floors, and the mutations that break them ─────────────

function selftest() {
  let pass = 0;
  const fails = [];
  const check = (name, fn) => {
    try { fn(); console.log(`  ok    ${name}`); pass += 1; }
    catch (e) { console.log(`  FAIL  ${name}\n        ${e.message}`); fails.push(name); }
  };
  const assert = (c, m) => { if (!c) throw new Error(m); };

  const doc = build();

  check("every code has a stage, a fix from FLOW-13's closed list and a panel-only flag", () => {
    for (const row of doc.flow13_table) {
      for (const k of MEMBERS) assert(k in row, `${row.code} has no ${k}`);
      assert(typeof row.stage === "string" && row.stage.length > 0, `${row.code} has no stage`);
      assert(FIXES.includes(row.fix), `${row.code}'s fix is ${JSON.stringify(row.fix)}`);
      assert(typeof row.panel_only === "boolean", `${row.code}'s panel-only flag is ${JSON.stringify(row.panel_only)}`);
    }
  });

  check("the table and its declared population are the same set, both ways", () => {
    const have = new Set(doc.flow13_table.map((r) => r.code));
    const want = new Set(doc.codes);
    assert(have.size === doc.flow13_table.length, "two rows name one code");
    for (const c of want) assert(have.has(c), `${c} is declared and has no row`);
    for (const c of have) assert(want.has(c), `${c} has a row and is not declared`);
  });

  check("no code the bot emits is panel-only", () => {
    const have = new Set(doc.flow13_table.map((r) => r.code));
    for (const c of PANEL_ONLY) assert(!have.has(c), `${c} is panel-only and has a row in the bot's own table`);
    for (const row of doc.flow13_table) assert(row.panel_only === false, `${row.code} is flagged panel-only`);
  });

  check("no service-path wait tells the author to comment, /recheck or answer in the issue", () => {
    for (const row of doc.flow13_table) {
      const d = policyCodeDef(row.code, { path: "service" });
      if (d && d.level === "wait") {
        assert(!CHANNEL.test(row.remedy), `${row.code}: ${JSON.stringify(row.remedy.match(CHANNEL)?.[0])} (FLOW-15)`);
      }
    }
  });

  check("a code B.7 names and this table cannot carry is recorded, not dropped", () => {
    assert(doc.codes_owed.codes.length > 0, "nothing is owed, on a tree where B.7's B_* codes carry no remedy");
    const have = new Set(doc.codes);
    for (const c of doc.codes_owed.codes) assert(!have.has(c), `${c} is both owed and emitted`);
    assert(/reg\.61a/.test(doc.codes_owed.owed_by), "the owed set does not name who owes it");
  });

  check("the floors", () => {
    assert(doc.flow13_table.length >= CODE_FLOOR, `${doc.flow13_table.length} codes, floor ${CODE_FLOOR}`);
    assert(new Set(doc.flow13_table.map((r) => r.stage)).size >= STAGE_FLOOR, "too few stages");
    assert(doc.codes_source.length === 2, "the source list is not the two files OPEN-OPS-8 names");
  });

  check("the output is a function of the sources alone", () => {
    assert(serialise(build()) === serialise(doc), "two builds of one tree differ");
  });

  check("it refuses to write the table anywhere but its own path", () => {
    for (const bad of ["schema/reason-codes-v1.json", "schema/codes.json", "tools/reason-codes-v1.json"]) {
      let threw = null;
      try { refuseBadOutput(path.join(REPO, bad)); } catch (e) { threw = e; }
      assert(threw, `${bad} was accepted as an output path`);
    }
    refuseBadOutput(path.join(REPO, "tools/codes-table.json"));
  });

  console.log(fails.length === 0
    ? `PASS  ${pass} passed, 0 failed  (${doc.flow13_table.length} codes, ${doc.codes_owed.codes.length} owed)`
    : `FAIL  ${pass} passed, ${fails.length} failed`);
  return fails.length === 0;
}

// ── CLI ─────────────────────────────────────────────────────────────────────

function main(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === "--selftest") opts.selftest = true;
    else if (a === "--print") opts.print = true;
    else if (a === "--out") opts.out = argv[++i];
    else if (a === "--check") opts.check = argv[++i];
    else { console.error(`unknown argument ${JSON.stringify(a)}`); process.exit(2); }
  }
  if (opts.selftest) process.exit(selftest() ? 0 : 1);

  let text;
  try {
    if (opts.out) refuseBadOutput(opts.out);
    text = serialise(build());
  } catch (e) {
    console.error(`FAIL  ${e.message}`);
    process.exit(1);
  }

  if (opts.check) {
    const on = fs.existsSync(opts.check) ? fs.readFileSync(opts.check, "utf8") : null;
    if (on === null) { console.error(`FAIL  ${opts.check} does not exist`); process.exit(1); }
    if (on !== text) {
      console.error(
        `FAIL  ${opts.check} is stale against bot/lib/codes.mjs and POLICY_CODES. Run: ` +
        `node tools/gen-codes-table.mjs --out ${opts.check} — and regenerate the token file with it ` +
        `(astra-plugins-ops tools/contract-tokens.mjs --codes), because FLOW-13's table is published there`);
      process.exit(1);
    }
    console.log(`ok    ${opts.check} is what the code tables say (${JSON.parse(on).codes.length} codes)`);
    return;
  }
  if (opts.out) {
    fs.mkdirSync(path.dirname(opts.out), { recursive: true });
    fs.writeFileSync(opts.out, text);
    console.log(`ok    wrote ${opts.out} (${JSON.parse(text).codes.length} codes)`);
    return;
  }
  process.stdout.write(text);
}

main(process.argv.slice(2));

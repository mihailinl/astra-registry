#!/usr/bin/env node
//
// FLOW-13's reason-code table, emitted from the bot's own code tables.
//
//   node tools/gen-codes-table.mjs --out tools/codes-table.json
//   node tools/gen-codes-table.mjs --check tools/codes-table.json
//   node tools/gen-codes-table.mjs --print
//   node tools/gen-codes-table.mjs --selftest
//
// **This program does not write the token file, and that is the whole shape of
// it.** Contract FLOW-13 publishes the table *inside* SCOPE-7's
// `schema/contract-tokens-v1.json` (0.13.0's n8), so that the panel, SCOPE-1's
// comparison and the canary read one artifact at one commit. But that file is
// generated by `astra-plugins-ops` `tools/contract-tokens.mjs`, which reads the
// contract and nothing else — and the codes are not in the contract, they are
// in this repository's `bot/lib/codes.mjs` and `POLICY_CODES`. So the two
// programs meet at a file:
//
//   this  →  tools/codes-table.json  →  contract-tokens.mjs --codes  →  the token file
//
// The registry plan's B-T2.3 still says this emitter writes into the token
// file directly. It cannot: that would put two writers on one artifact, in two
// repositories, and the second one to run would silently drop the first one's
// work. The intermediate is the correction, and `tools/codes-table.json` is its
// path — chosen here because the plan names none anywhere (measured absent in
// B-T2.3's block, in RC-R2-1's, and in the ops generator). It is committed
// rather than built on demand, because `astra-plugins-ops`'s own
// `tools/check-contract.mjs` regenerates the token file from a registry
// checkout to compare it, and a checker that has to execute this repository's
// code to do that is a checker that cannot run from a clean checkout.
//
// **`codes` is not decoration, and it is the reason this file has the shape it
// has.** The ops generator's first `--codes` merge took a bare array of rows
// and asserted every row was complete. A table with one code's row deleted
// PASSED — it had to, because that program runs in another repository and
// cannot read `bot/lib/codes.mjs`, so "one entry per code the bot emits" is a
// claim only this program can make. So this program makes it: `codes` is the
// complete list of every code name its sources define, `codes_source` is the
// files it read, and the merge compares the table with that list **in both
// directions**. A deleted row is then a row missing from a population the same
// file declares, and a row nobody declares is a row naming no code.
//
// Nothing here reads a clock, a directory listing or a network: the output is
// a function of the two source modules alone.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { CODES, PANEL_CODES } from "../bot/lib/codes.mjs";
import { POLICY_CODES, policyCodeDef } from "../bot/lib/policy.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The two files OPEN-OPS-8 names, and the only two this program reads. */
const SOURCES = ["bot/lib/codes.mjs", "bot/lib/policy/constants.mjs"];

/** FLOW-13's closed list. Nothing else may appear in a `fix`. */
const FIXES = ["recheck", "new_tag", "moderator", "registry", "none"];

/**
 * The levels a code may carry: `bot/lib/codes.mjs`'s `Level`, and `wait`, the
 * level `bot/lib/policy/constants.mjs` gives B.7's waits and the one row that
 * carries it, `W_REGISTRY_UNACKNOWLEDGED`.
 */
const LEVELS = ["error", "review", "warn", "note", "pass", "skip", "wait"];

/** FLOW-13's six members, plus the code itself. */
const MEMBERS = ["code", "level", "stage", "fix", "panel_only", "title", "remedy"];

// The stages at which every finding is a property of bytes the build
// attestation already covers. A Recheck re-runs the same tag (FLOW-4), so at
// these stages `recheck` is never the answer — the same bytes are read again
// and reach the same verdict. This is the rule `bot/lib/codes.mjs`'s header
// states, written here as something that fails rather than something that is
// merely documented; it is the check that would have caught FLOW-13's own
// worked example going the wrong way (`B_UNBOUND` is `new_tag`, not
// `recheck`, and for exactly this reason).
const ATTESTED_STAGES = ["bundle", "manifest", "metadata", "version", "rpc-scan", "names"];

// B.7's panel-only details and the wait only the service shows. FLOW-13's
// panel-only flag exists to mark these; no code the bot emits may be one, and
// asserting that is what turns the flag from a claim into a measurement.
const PANEL_ONLY = ["B_BINDING_INVALID", "B_ACCOUNT_INELIGIBLE", "W_REGISTRY_UNACKNOWLEDGED"];

// The `fix` contract B.7 states by name (2.5.0): `new_tag` for the three
// binding refusals and the token half of the panel-only detail, because the
// line is read at the attested commit (ID-22); `recheck` for the account half,
// which the account's own eligibility clears; `moderator` for the two identity
// refusals (ID-41); `registry` for the one wait only the service shows.
const B7_FIXES = {
  B_UNBOUND: "new_tag",
  B_BINDING_MALFORMED: "new_tag",
  B_BINDING_UNUSABLE: "new_tag",
  B_BINDING_INVALID: "new_tag",
  B_ACCOUNT_INELIGIBLE: "recheck",
  B_OWNER_CHANGED: "moderator",
  B_REPOSITORY_RECYCLED: "moderator",
  W_REGISTRY_UNACKNOWLEDGED: "registry",
};

// The level and `fix` decided for the ten codes the contract gives no `fix`.
// The coordinator decided each `fix` under the owner's standing grant of
// 2026-09-23, adopting lane S10's proposals. It also decided both `A_*` levels.
// Lane S15 chose the `M_*` levels from `bot/lib/codes.mjs`'s own definitions,
// on 2026-09-24:
//   * `error` where the versions or the listing stop being offered (§7.2:
//     `yanked`, `unlisted`; an advisory that refuses or stops);
//   * `warn` where the listing stays listed and says so (an advisory `warn`,
//     "badged"; a revoked token, whose next release answers with its own code);
//   * `note` for a reversal or a reset, which report something done.
// They are held apart from B7_FIXES because they are a decision, not a
// contract sentence. The day a contract version states one, it moves to
// B7_FIXES with its clause.
const DECIDED = {
  A_BINDING_REVOKE: { level: "note", fix: "none" },
  A_REMOVAL_REQUEST: { level: "note", fix: "none" },
  M_YANK: { level: "error", fix: "none" },
  M_DELIST: { level: "error", fix: "moderator" },
  M_RELIST: { level: "note", fix: "none" },
  M_DEPRECATE: { level: "warn", fix: "moderator" },
  M_REVOKE: { level: "error", fix: "moderator" },
  M_UNREVOKE: { level: "note", fix: "none" },
  M_BINDING_REVOKE: { level: "warn", fix: "none" },
  M_IDENTITY_RESET: { level: "note", fix: "none" },
};

// One `warn` a moderator lifts. The rule in `build()` reads `warn` as a check
// finding: it blocks nothing, so nothing clears it. §7.2's `M_DEPRECATE` is not
// a finding. It writes an advisory `warn` ("badged"), and the daemon's
// `RevocationAction::Warn` badges and does nothing else (contract 2.14.0), so
// the listing stays listed, which is `warn`. That advisory stands until a
// moderator's `M_UNREVOKE` deletes it (§7.2), which is `moderator`. The
// selftest holds this list to the token file's §7.2 cells that write an
// advisory `warn`, so a second entry needs a second such cell.
const WARN_A_MODERATOR_LIFTS = ["M_DEPRECATE"];

/** SCOPE-7's token file, read by the selftest alone for B.7's population. */
const TOKEN_FILE = "schema/contract-tokens-v1.json";
/** 38 reason codes and waits at contract 2.7.0. */
const TOKEN_CODE_FLOOR = 30;
/** The waits the token file gives the registry: eight at contract 2.14.0. */
const REPORTED_WAIT_FLOOR = 8;
/** The parties that mean "the bot reports it" in a token-file entry's `emitter`. */
const OURS = ["registry", "bot"];

// FLOW-15: a remedy on the service path may not tell an author to comment, to
// `/recheck`, or to say anything "in the issue" — on that path there is no
// issue and there is no comment box. Applied to the codes the service turns
// into waits (FLOW-72), which is what `policyCodeDef(code, {path: "service"})`
// answers. The rest of FLOW-15's scrub is the legacy path's and is gated at
// ROLL-44 by FLOW-15's own Check line.
const CHANNEL = /\/recheck|comment|in the issue/i;

/** Why a wait the bot reports carries no row, verbatim for each (lane S15, 2026-09-24). */
const WAIT_ABSENT_REASON = "FLOW-10 renders it; B.7 gives the table only service-only waits";

// B.7 names codes this table might not carry, and each absence is recorded
// rather than left to be discovered. The selftest reads the population from the
// token file, so a B.7 code that is neither a row, nor owed, nor recorded absent
// is red. There are two kinds of absence, kept apart:
//
//   * **owed**: the code needs a row, and a contract sentence it waits on is
//     missing. Each owed code names its own reason.
//   * **absent**: the code has no row, and the contract says so. The only such
//     codes are B.7's waits that the bot reports.
//
// Until 2026-09-24 twenty-one codes were owed to reg.61a (registry plan
// B-T3.3b), which landed as #271 and wrote none of them. Lane S10 wrote the
// thirteen whose `fix` a contract clause states (#336). Lane S15 wrote the ten
// whose level and `fix` are DECIDED above, and recorded the eight waits as
// absent. Nothing is owed at this commit. The member stays, so that the next
// code a contract version adds without a `fix` has a place that is not a row.
const OWED = {
  owed_by: "the contract sentence each code's reason names",
  why:
    "FLOW-13 requires one full entry per reason code, and `fix` is a closed list naming what clears the code. " +
    "For an owed code the contract states no `fix`, so a row here would be this repository's answer to a " +
    "contract question.",
  codes: [],
  each: {},
};

// B.7's waits that the bot reports: the token file gives each of them the
// registry as emitter. W_REGISTRY_UNACKNOWLEDGED is not here, because only the
// service shows it, and it has a panel-only row (`PANEL_CODES`).
const ABSENT_WAITS = [
  "W_LEASE_EXPIRED", "W_ELIGIBILITY_UNREADABLE", "W_NOTICE_PENDING", "W_GITHUB_RATE_LIMITED",
  "W_SERVICE_UNREACHABLE", "W_MODERATION_HOLD", "W_ALERT_UNDELIVERED", "W_OPERATOR_WINDOW",
];
const ABSENT = {
  why:
    "B.7: FLOW-13's table lists \"the codes … and the waits only the service shows\". Each of these is a wait " +
    "the bot reports, in a result's `wait` or by answering with no record (FLOW-72). FLOW-10 shows every wait by " +
    "its start, cause and earliest retry, never from the table. So none of them carries a row, and each is " +
    "recorded here so that it does not read as dropped.",
  codes: ABSENT_WAITS,
  each: Object.fromEntries(ABSENT_WAITS.map((c) => [c, WAIT_ABSENT_REASON])),
};

/** Floors. Below these the walk has failed, not the vocabulary shrunk. */
const CODE_FLOOR = 100;
const STAGE_FLOOR = 10;

class Problems {
  constructor() { this.list = []; }
  fail(where, what) { this.list.push(`${where}: ${what}`); }
}

/**
 * The table, and the population it is a table of.
 *
 * Rows are sorted by code so that the output is a function of the sources and
 * not of two objects' insertion orders.
 */
export function build() {
  const p = new Problems();
  const rows = [];
  const seen = new Map();

  const add = (code, def, source, panel = false) => {
    const prior = seen.get(code);
    if (prior) {
      // Two tables declaring one code is allowed — `R_FIRST_LISTING` and
      // `R_IDENTITY_CHANGED` are in both — but two ANSWERS are not. The panel
      // reads one row, so the row it reads must not depend on which file the
      // emitter happened to walk second. Title and remedy are prose about two
      // different moments and are allowed to differ; `level`, `stage` and
      // `fix` are what the panel routes on and must not. On its first run this
      // check found the two duplicates carrying stage `version` in one table
      // and `policy` in the other, which had been true on `main` since the
      // policy module was split out.
      for (const k of ["level", "stage", "fix"]) {
        if (prior.def[k] !== def[k]) {
          p.fail(code, `${source} says ${k} ${JSON.stringify(def[k])} and ${prior.source} says ` +
            `${JSON.stringify(prior.def[k])}. One code, two answers, and the panel reads one row`);
        }
      }
      return;
    }
    seen.set(code, { def, source });

    for (const k of ["level", "stage", "fix", "title", "remedy"]) {
      if (typeof def[k] !== "string" || def[k].length === 0) {
        p.fail(code, `${source} gives it no ${k}. FLOW-13's table is one FULL entry per code`);
      }
    }
    if (!LEVELS.includes(def.level)) p.fail(code, `level ${JSON.stringify(def.level)} is not one of ${LEVELS.join(", ")}`);
    if (!FIXES.includes(def.fix)) {
      p.fail(code, `fix ${JSON.stringify(def.fix)} is not one of FLOW-13's closed list ${FIXES.join(", ")}`);
    }

    // The rule, as a check. See ATTESTED_STAGES above.
    if (def.level === "review" && def.fix !== "moderator") {
      p.fail(code, `is level review and fix ${JSON.stringify(def.fix)}; a review waits on a person, so it is cleared by \`moderator\``);
    }
    const liftedWarn = def.level === "warn" && def.fix === "moderator" && WARN_A_MODERATOR_LIFTS.includes(code);
    if (["warn", "note", "pass"].includes(def.level) && def.fix !== "none" && !liftedWarn) {
      p.fail(code, `is level ${def.level} and fix ${JSON.stringify(def.fix)}; nothing is blocked, so nothing clears it`);
    }
    if (def.level === "error" && ATTESTED_STAGES.includes(def.stage) && def.fix === "recheck") {
      p.fail(code, `is an error at stage ${def.stage} with fix \`recheck\`. A Recheck re-runs the same tag ` +
        `(FLOW-4) and reads the same attested bytes, so it reaches the same verdict for ever`);
    }

    // `panel_only` is derived, not declared: true for a row out of
    // `PANEL_CODES` and false for every other. Every code in the two emitting
    // tables is one the bot emits, which is exactly what panel-only denies, so
    // one of B.7's panel-only codes declared there is refused; and a key in
    // `PANEL_CODES` that B.7 does not make panel-only is refused too, because
    // that table is the one place a row may exist without the bot emitting it.
    const panelOnly = panel;
    if (!panel && (def.panel_only === true || PANEL_ONLY.includes(code))) {
      p.fail(code, `is panel-only and is declared in ${source}. The panel-only flag marks B.7's ` +
        `panel-only details and the waits only the service shows; a bot module emitting one would ` +
        `publish what \`B_BINDING_UNUSABLE\` withholds (BOT-89)`);
    }
    if (panel && !PANEL_ONLY.includes(code)) {
      p.fail(code, `is declared in ${source}, which holds B.7's panel-only codes alone ` +
        `(${PANEL_ONLY.join(", ")}); a row there is one the bot never emits`);
    }

    // FLOW-15, on the path it binds.
    const onService = policyCodeDef(code, { path: "service" });
    if (onService && onService.level === "wait" && CHANNEL.test(def.remedy)) {
      p.fail(code, `is a wait on the service path (FLOW-72) and its remedy names a channel that path ` +
        `does not have: ${JSON.stringify(def.remedy.match(CHANNEL)[0])} (FLOW-15)`);
    }

    rows.push({
      code,
      level: def.level,
      stage: def.stage,
      fix: def.fix,
      panel_only: panelOnly,
      title: def.title,
      remedy: def.remedy.replace(/\s+/g, " ").trim(),
    });
  };

  // `POLICY_CODES` is walked first, so its title and remedy win for a code
  // declared twice. That is not a preference: `policyCodeDef()` resolves
  // `POLICY_CODES` before anything else, so this is the same answer the bot
  // itself gives when it reports one of those two codes.
  for (const [code, def] of Object.entries(POLICY_CODES)) add(code, def, "bot/lib/policy/constants.mjs");
  for (const [code, def] of Object.entries(CODES)) add(code, def, "bot/lib/codes.mjs");
  // Last, so that a panel-only code also declared in an emitting table is
  // refused there, under that table's name, rather than read here first.
  for (const [code, def] of Object.entries(PANEL_CODES)) add(code, def, "bot/lib/codes.mjs (PANEL_CODES)", true);

  rows.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));

  if (rows.length < CODE_FLOOR) {
    p.fail("floor", `${rows.length} codes read from ${SOURCES.length} sources; the floor is ${CODE_FLOOR}. ` +
      `A vocabulary this small is a broken import, not a smaller bot`);
  }
  const stages = new Set(rows.map((r) => r.stage));
  if (stages.size < STAGE_FLOOR) {
    p.fail("floor", `${stages.size} distinct stages; the floor is ${STAGE_FLOOR}`);
  }

  if (p.list.length) {
    const e = new Error(
      `${p.list.length} problem(s) in the reason-code table, so it was NOT emitted:\n  ` + p.list.join("\n  "));
    e.problems = p.list;
    throw e;
  }

  return {
    readme: [
      "FLOW-13's reason-code table, emitted by tools/gen-codes-table.mjs from the two files in `codes_source` and from nothing else.",
      "This file is an INTERMEDIATE and not the published interface. The published one is FLOW-13's table inside SCOPE-7's `schema/contract-tokens-v1.json`, where astra-plugins-ops `tools/contract-tokens.mjs --codes <this file>` merges it (0.13.0's n8).",
      "`codes` is the complete list of every code name those sources define. It is here so the merge can compare the table with the population in BOTH directions: without it a deleted row is indistinguishable from a code that does not exist, which was watched, and passed.",
      "`codes_owed` names the B.7 codes this table cannot carry yet and who owes their title and remedy. An absent code is recorded, never silently dropped.",
      "`codes_absent` names the B.7 codes that have no row because the contract gives them none: the waits the bot reports, which FLOW-10 renders from the result and not from this table.",
    ],
    codes_source: SOURCES,
    codes: rows.map((r) => r.code),
    codes_owed: OWED,
    codes_absent: ABSENT,
    flow13_table: rows,
  };
}

/** Where this program may write. See canary (4) in B-T2.3. */
function refuseBadOutput(out) {
  const rel = path.relative(REPO, path.resolve(out)).split(path.sep).join("/");
  if (rel.startsWith("schema/")) {
    throw new Error(
      `refusing to write ${rel}. FLOW-13's table is published inside SCOPE-7's token file and nowhere ` +
      `else (0.13.0's n8); a second artifact under schema/ is the unpinned second copy that decision ` +
      `removed, and a twelfth file under schema/ is a contract MINOR besides (TRUST-31)`);
  }
  if (path.basename(rel) === "reason-codes-v1.json") {
    throw new Error(
      `refusing to write ${rel}. \`schema/reason-codes-v1.json\` is the file the 0.12.0 plan created and ` +
      `0.13.0 deleted (n8). Writing it under any directory recreates the two-artifact problem under a ` +
      `name that makes it look published`);
  }
}

const serialise = (doc) => JSON.stringify(doc, null, 2) + "\n";

// ── the selftest: the floors, and the mutations that break them ─────────────

function selftest() {
  let pass = 0;
  const fails = [];
  const check = (name, fn) => {
    try { fn(); console.log(`  ok    ${name}`); pass += 1; }
    catch (e) { console.log(`  FAIL  ${name}\n        ${e.message}`); fails.push(name); }
  };
  const assert = (c, m) => { if (!c) throw new Error(m); };

  const doc = build();

  check("every code has a stage, a fix from FLOW-13's closed list and a panel-only flag", () => {
    for (const row of doc.flow13_table) {
      for (const k of MEMBERS) assert(k in row, `${row.code} has no ${k}`);
      assert(typeof row.stage === "string" && row.stage.length > 0, `${row.code} has no stage`);
      assert(FIXES.includes(row.fix), `${row.code}'s fix is ${JSON.stringify(row.fix)}`);
      assert(typeof row.panel_only === "boolean", `${row.code}'s panel-only flag is ${JSON.stringify(row.panel_only)}`);
    }
  });

  check("the table and its declared population are the same set, both ways", () => {
    const have = new Set(doc.flow13_table.map((r) => r.code));
    const want = new Set(doc.codes);
    assert(have.size === doc.flow13_table.length, "two rows name one code");
    for (const c of want) assert(have.has(c), `${c} is declared and has no row`);
    for (const c of have) assert(want.has(c), `${c} has a row and is not declared`);
  });

  // FLOW-13's sixth member, both ways. B.7's panel-only details and the wait
  // only the service shows each carry a row flagged panel-only, out of
  // `PANEL_CODES` and never out of the two tables the bot emits from; every
  // other row is flagged false. Until 2026-09-24 this read "no code the bot
  // emits is panel-only" and asserted only the second half, so the table
  // carried no panel-only row at all and the check was green for it.
  check("B.7's panel-only codes, and only they, carry a row flagged panel-only", () => {
    const byCode = new Map(doc.flow13_table.map((r) => [r.code, r]));
    for (const c of PANEL_ONLY) {
      assert(byCode.has(c), `${c} is one of B.7's panel-only codes and has no FLOW-13 row`);
      assert(byCode.get(c).panel_only === true, `${c} is one of B.7's panel-only codes and its row is not flagged panel-only`);
      assert(!Object.hasOwn(CODES, c) && !Object.hasOwn(POLICY_CODES, c),
        `${c} is panel-only and is declared in a table the bot emits from (BOT-89)`);
    }
    for (const row of doc.flow13_table) {
      if (row.panel_only) assert(PANEL_ONLY.includes(row.code), `${row.code} is flagged panel-only and B.7 does not make it so`);
    }
  });

  // The `fix` values contract B.7 states outright (2.5.0), held here because
  // the token file carries only the table this program emits, so nothing else
  // can say the table has drifted from the sentence.
  check("the fix B.7 states for a code is the fix its row carries", () => {
    const byCode = new Map(doc.flow13_table.map((r) => [r.code, r]));
    for (const [code, fix] of Object.entries(B7_FIXES)) {
      assert(byCode.has(code), `B.7 states fix \`${fix}\` for ${code}, and the table carries no row for it`);
      assert(byCode.get(code).fix === fix, `B.7 states fix \`${fix}\` for ${code}, and its row says \`${byCode.get(code).fix}\``);
    }
  });

  check("no service-path wait tells the author to comment, /recheck or answer in the issue", () => {
    for (const row of doc.flow13_table) {
      const d = policyCodeDef(row.code, { path: "service" });
      if (d && d.level === "wait") {
        assert(!CHANNEL.test(row.remedy), `${row.code}: ${JSON.stringify(row.remedy.match(CHANNEL)?.[0])} (FLOW-15)`);
      }
    }
  });

  // The check's name was a claim until 2026-09-24: it asserted that the owed
  // list was non-empty and disjoint from the rows, and never asked B.7. So
  // §7.2's eight moderation codes, which the token file lists as reason codes,
  // were neither rows nor owed, and the check was green. It now reads the
  // population from the token file, whose `reason_code` and `wait` entries are
  // generated from B.7 by astra-plugins-ops and never from this program.
  // The token file, read once, and the B.7 entries in it that are in force.
  const token = JSON.parse(fs.readFileSync(path.join(REPO, TOKEN_FILE), "utf8"));
  const tokenCodes = [...(token.entries ?? []), ...(token.service_only ?? [])]
    .filter((e) => (e?.kind === "reason_code" || e?.kind === "wait") && e.state !== "retired");

  check("a code B.7 names and this table cannot carry is recorded, not dropped", () => {
    const listed = tokenCodes.map((e) => e.name);
    assert(listed.length >= TOKEN_CODE_FLOOR, `${TOKEN_FILE} lists ${listed.length} reason codes and waits, under the ` +
      `floor of ${TOKEN_CODE_FLOOR}; a reader that finds fewer has stopped reading B.7`);
    const have = new Set(doc.codes);
    const owed = new Set(doc.codes_owed.codes);
    const absent = new Set(doc.codes_absent?.codes ?? []);
    const dropped = listed.filter((c) => !have.has(c) && !owed.has(c) && !absent.has(c));
    assert(dropped.length === 0,
      `${TOKEN_FILE} lists ${dropped.join(", ")}, which have no FLOW-13 row and are neither owed nor recorded absent`);
    for (const c of owed) assert(!have.has(c), `${c} is both owed and emitted`);
    for (const c of owed) assert(!absent.has(c), `${c} is both owed and recorded absent`);
    const each = doc.codes_owed.each ?? {};
    for (const c of owed) {
      assert(typeof each[c] === "string" && each[c].length > 0, `${c} is owed and \`codes_owed.each\` gives no reason for it`);
    }
    for (const c of Object.keys(each)) assert(owed.has(c), `\`codes_owed.each\` gives a reason for ${c}, which is not owed`);
  });

  // B.7 gives FLOW-13's table "the codes … and the waits only the service
  // shows". The token file says which party emits each wait. So a wait it gives
  // the registry is one the bot reports. That wait has no row: FLOW-10 renders
  // it from the result, by its start, cause and earliest retry. It is recorded
  // under `codes_absent` so that the check above can tell it from a dropped
  // code. A wait only the service shows has a row, flagged panel-only. Only
  // such a wait may be recorded absent. Otherwise a reason code parked there
  // would pass as a wait, and nothing would ever write its row.
  check("a wait the bot reports is recorded absent, and a wait only the service shows has a row (B.7)", () => {
    const absent = doc.codes_absent;
    assert(absent && Array.isArray(absent.codes) && absent.each && typeof absent.each === "object",
      "the table carries no `codes_absent` record, so B.7's waits the bot reports are neither rows nor recorded");
    const byCode = new Map(doc.flow13_table.map((r) => [r.code, r]));
    const waits = tokenCodes.filter((e) => e.kind === "wait");
    const reported = waits.filter((e) => (e.emitter ?? []).some((p) => OURS.includes(p))).map((e) => e.name);
    const serviceOnly = waits.filter((e) => !(e.emitter ?? []).some((p) => OURS.includes(p))).map((e) => e.name);
    assert(reported.length >= REPORTED_WAIT_FLOOR, `${TOKEN_FILE} gives the registry ${reported.length} wait(s), under ` +
      `the floor of ${REPORTED_WAIT_FLOOR}; a reader that finds fewer has stopped reading B.7's waits`);
    assert(serviceOnly.length >= 1, `${TOKEN_FILE} lists no wait only the service shows; W_REGISTRY_UNACKNOWLEDGED was one at 2.14.0`);
    const set = new Set(absent.codes);
    assert(set.size === absent.codes.length, "`codes_absent.codes` names one code twice");
    for (const c of reported) {
      assert(set.has(c), `${c} is a wait the bot reports (${TOKEN_FILE} gives it the registry) and is not recorded absent`);
      assert(!byCode.has(c), `${c} is a wait the bot reports and carries a FLOW-13 row; B.7 gives the table only the waits the service alone shows`);
      assert(absent.each[c] === WAIT_ABSENT_REASON,
        `${c}'s absence gives ${JSON.stringify(absent.each[c])} as its reason, not ${JSON.stringify(WAIT_ABSENT_REASON)}`);
    }
    for (const c of serviceOnly) {
      assert(byCode.has(c) && byCode.get(c).panel_only === true, `${c} is a wait only the service shows and has no panel-only row`);
    }
    for (const c of set) {
      assert(reported.includes(c), `${c} is recorded absent and is not a wait ${TOKEN_FILE} gives the registry; only those have no row`);
    }
    for (const c of Object.keys(absent.each)) assert(set.has(c), `\`codes_absent.each\` gives a reason for ${c}, which is not recorded absent`);
  });

  // The ten codes the contract gives no `fix`. Their level and `fix` are a
  // decision (DECIDED above), held here as B.7's are, because the token file
  // carries only what this program emits.
  check("the level and fix decided for a code the contract gives no fix are what its row carries", () => {
    const byCode = new Map(doc.flow13_table.map((r) => [r.code, r]));
    assert(Object.keys(DECIDED).length === 10, `DECIDED holds ${Object.keys(DECIDED).length} codes; the decision named ten`);
    for (const [code, want] of Object.entries(DECIDED)) {
      assert(!Object.hasOwn(B7_FIXES, code), `${code} is in DECIDED and in B7_FIXES; a code whose fix the contract states is not a decision`);
      assert(byCode.has(code), `${code}'s level and fix are decided, and the table carries no row for it`);
      const row = byCode.get(code);
      assert(row.fix === want.fix, `${code}'s fix was decided as \`${want.fix}\`, and its row says \`${row.fix}\``);
      assert(row.level === want.level, `${code}'s level was decided as \`${want.level}\`, and its row says \`${row.level}\``);
    }
  });

  check("a warn a moderator lifts is exactly a §7.2 code that writes an advisory `warn`", () => {
    const cells = tokenCodes
      .filter((e) => e.kind === "reason_code" && typeof e.artefact === "string" && /^advisory `warn`/.test(e.artefact))
      .map((e) => e.name).sort();
    assert(cells.length >= 1, `${TOKEN_FILE} carries no §7.2 cell that writes an advisory \`warn\`; M_DEPRECATE's did at 2.14.0`);
    assert(JSON.stringify([...WARN_A_MODERATOR_LIFTS].sort()) === JSON.stringify(cells),
      `WARN_A_MODERATOR_LIFTS is ${JSON.stringify(WARN_A_MODERATOR_LIFTS)}, and the §7.2 cells that write an advisory \`warn\` ` +
      `are ${JSON.stringify(cells)}`);
    const byCode = new Map(doc.flow13_table.map((r) => [r.code, r]));
    for (const c of WARN_A_MODERATOR_LIFTS) {
      const row = byCode.get(c);
      assert(row && row.level === "warn" && row.fix === "moderator",
        `${c} is excepted as a warn a moderator lifts, and its row is ${row ? `${row.level}/${row.fix}` : "missing"}`);
    }
  });

  check("the floors", () => {
    assert(doc.flow13_table.length >= CODE_FLOOR, `${doc.flow13_table.length} codes, floor ${CODE_FLOOR}`);
    assert(new Set(doc.flow13_table.map((r) => r.stage)).size >= STAGE_FLOOR, "too few stages");
    assert(doc.codes_source.length === 2, "the source list is not the two files OPEN-OPS-8 names");
  });

  check("the output is a function of the sources alone", () => {
    assert(serialise(build()) === serialise(doc), "two builds of one tree differ");
  });

  check("it refuses to write the table anywhere but its own path", () => {
    for (const bad of ["schema/reason-codes-v1.json", "schema/codes.json", "tools/reason-codes-v1.json"]) {
      let threw = null;
      try { refuseBadOutput(path.join(REPO, bad)); } catch (e) { threw = e; }
      assert(threw, `${bad} was accepted as an output path`);
    }
    refuseBadOutput(path.join(REPO, "tools/codes-table.json"));
  });

  console.log(fails.length === 0
    ? `PASS  ${pass} passed, 0 failed  (${doc.flow13_table.length} codes, ${doc.codes_owed.codes.length} owed, ${doc.codes_absent.codes.length} absent)`
    : `FAIL  ${pass} passed, ${fails.length} failed`);
  return fails.length === 0;
}

// ── CLI ─────────────────────────────────────────────────────────────────────

function main(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === "--selftest") opts.selftest = true;
    else if (a === "--print") opts.print = true;
    else if (a === "--out") opts.out = argv[++i];
    else if (a === "--check") opts.check = argv[++i];
    else { console.error(`unknown argument ${JSON.stringify(a)}`); process.exit(2); }
  }
  if (opts.selftest) process.exit(selftest() ? 0 : 1);

  let text;
  try {
    if (opts.out) refuseBadOutput(opts.out);
    text = serialise(build());
  } catch (e) {
    console.error(`FAIL  ${e.message}`);
    process.exit(1);
  }

  if (opts.check) {
    const on = fs.existsSync(opts.check) ? fs.readFileSync(opts.check, "utf8") : null;
    if (on === null) { console.error(`FAIL  ${opts.check} does not exist`); process.exit(1); }
    if (on !== text) {
      console.error(
        `FAIL  ${opts.check} is stale against bot/lib/codes.mjs and POLICY_CODES. Run: ` +
        `node tools/gen-codes-table.mjs --out ${opts.check} — and regenerate the token file with it ` +
        `(astra-plugins-ops tools/contract-tokens.mjs --codes), because FLOW-13's table is published there`);
      process.exit(1);
    }
    console.log(`ok    ${opts.check} is what the code tables say (${JSON.parse(on).codes.length} codes)`);
    return;
  }
  if (opts.out) {
    fs.mkdirSync(path.dirname(opts.out), { recursive: true });
    fs.writeFileSync(opts.out, text);
    console.log(`ok    wrote ${opts.out} (${JSON.parse(text).codes.length} codes)`);
    return;
  }
  process.stdout.write(text);
}

main(process.argv.slice(2));

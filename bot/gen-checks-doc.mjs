function table() {
  const lines = [];
  for (const [stage, title, blurb] of STAGES) {
    const rows = Object.entries(CODES).filter(([, def]) => def.stage === stage);
    if (rows.length === 0) continue;
    lines.push(`### ${title}`, "", blurb, "", "| Code | Level | Meaning | What to do |", "|---|---|---|---|");
    for (const [code, def] of rows) {
      const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
      lines.push(`| \`${code}\` | ${def.level} | ${cell(def.title)} | ${cell(def.remedy)} |`);
    }
    lines.push("");
  }
  const known = new Set(STAGES.map(([s]) => s));
  const orphans = Object.entries(CODES).filter(([, d]) => !known.has(d.stage));
  if (orphans.length) {
    lines.push("### Uncategorised", "", "A stage that is not in the generator's table — fix `bot/gen-checks-doc.mjs`.", "", "| Code | Stage |", "|---|---|");
    for (const [code, def] of orphans) lines.push(`| \`${code}\` | ${def.stage} |`);
    lines.push("");
  }
  return lines.join("\n");
}


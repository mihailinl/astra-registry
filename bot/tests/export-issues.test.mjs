#!/usr/bin/env node
// `bot/export-issues.mjs`: MIG-21's historic export.  `node bot/tests/export-issues.test.mjs`
//
// Two things are being asserted here and they are not the same thing.
//
// **That the grammar matches what this registry actually posted.** Not a
// grammar somebody typed into a test beside the one they typed into the parser
// — the first block below RENDERS the four decisions with `bot/ingest.mjs` and
// `bot/lib/policy/comment.mjs`, the modules that wrote every historic comment,
// and reads them back. A heading changed in either renderer breaks this file,
// which is the only way an export of a closed archive can be kept honest:
// after ROLL-42 switches Issues off there is no corpus left to re-run against,
// so the coupling has to be watched while the corpus still exists.
//
// **That nothing a stranger typed can cross.** The fixture thread carries
// logins, an email, a paragraph of free text and a comment that imitates the
// bot's marker byte for byte. The assertions are over the SERIALISED output —
// every planted needle is searched for in the JSON, rather than checked member
// by member, because a member-by-member check only ever covers the members
// somebody thought of.
//
// Nothing here touches the network.


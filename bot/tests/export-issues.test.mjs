/**
 * DEC-7's member list, as contract 0.13.0 §2 writes it.
 *
 * Copied deliberately rather than imported: `schema/decision-v1.json` is
 * B-T2.1's — and **it IS on `main`**: all three of B-T2.1's schemas are tracked,
 * and this sentence said "is not on `main`" until 2026-09-22. The point of the
 * assertion is unchanged: this export composes nothing the contract did not
 * name.
 *
 * WHAT THE STALENESS COSTS HERE IS SPECIFIC: the old sentence ended "when the
 * schema lands, RC-R3-2 compares the two directions" — a future tense over a
 * thing that has happened. **RC-R3-2's comparison is therefore owed now, and
 * nothing is tracking that it is owed**, because the only note saying so
 * described it as waiting for a landing that already occurred.
 */
const DEC7_MEMBERS = new Set([
  "schema", "decision_id", "submission_id", "decided_at", "actor", "moderator", "trigger", "plugin_id",
  "version", "repo", "repository_id", "repository_owner_id", "tag", "commit", "artifact_digests",
  "fingerprint", "state", "reasons", "category", "appeal_of", "outcome", "declared_interest",
  "publish_after", "run", "advisory",
]);

await test("one migration record per fact, actor system, and only DEC-7's members", () => {
  const { facts } = exportFacts(fixtureCorpus());
  const composed = composeRecords(facts);
  assert.equal(composed.length, facts.length, "MIG-21: one record each");
  for (const { key, record } of composed) {
    assert.match(key, /^history:[^@]+@[^:]+:[0-9T:-]+Z:(refused|approved)$/, "BOT-35's `history:` key (contract 2.5.0)");
    assert.equal(record.actor, "system", "PRIV-10: every historic approver is `system`");
    assert.equal(record.trigger, "migration", "DEC-7's trigger, reserved for MIG-20 and MIG-21");
    assert.ok(record.state === "refused" || record.state === "approved",
      "MIG-21: never `published`, so an export record can never form MIG-20's baseline");
    assert.equal(record.schema, undefined, "B-T2.2's writer stamps the schema");
    assert.equal(record.decision_id, undefined, "and derives the id, in one place");
    for (const member of Object.keys(record)) {
      assert.ok(DEC7_MEMBERS.has(member), `\`${member}\` is not a member DEC-7 names`);
    }
  }
});

await test("a login written into a record is refused by the allowlist, not by a blocklist", () => {
  const record = { decided_at: "2026-08-20T07:19:05Z", actor: "system", trigger: "migration", repo: "a/b", tag: "v1", state: "approved" };
  assert.doesNotThrow(() => refuseUncomposable(record));
  assert.throws(() => refuseUncomposable({ ...record, login: "Belnash3" }), /not a member this export composes/,
    "this is the `comment.user.login` mutation the plan asks to be watched");
  assert.throws(() => refuseUncomposable({ ...record, moderator: "Belnash3" }),
    /not a member this export composes/,
    "and `moderator` is a DEC-7 member that this export must still never write");
  assert.throws(() => refuseUncomposable({ ...record, actor: "moderator" }), /does not match its own grammar/);
  assert.throws(() => refuseUncomposable({ ...record, state: "published" }), /does not match its own grammar/);
});

await test("two decisions about one tag get two `history:` keys and two records; one decision read twice is refused", () => {
  // Until contract 2.5.0 both facts below shared `migration:a/b@v1`, and
  // composing them was refused: the live archive had 24 such keys across 102
  // facts on 2026-09-24. `history:` adds the time and the state, so MIG-21's
  // "one record each" holds, and over that archive no key is shared.
  const facts = [
    { repository: "a/b", tag: "v1", plugin_id: null, version: null, state: "refused", date: "2026-08-01T00:00:00Z", reasons: [] },
    { repository: "a/b", tag: "v1", plugin_id: "bee", version: "1.0.0", state: "approved", date: "2026-08-02T00:00:00Z", reasons: [] },
  ];
  assert.deepEqual(keyCollisions(facts), []);
  assert.deepEqual(composeRecords(facts).map((c) => c.key), [
    "history:a/b@v1:2026-08-01T00:00:00Z:refused",
    "history:a/b@v1:2026-08-02T00:00:00Z:approved",
  ]);
  // The same decision twice, same time and same state, is one line of the
  // archive read twice. Writing one record for it would hide the double read,
  // so it is still refused, by key.
  const twice = [facts[0], { ...facts[0] }];
  assert.deepEqual(keyCollisions(twice), [{ key: "history:a/b@v1:2026-08-01T00:00:00Z:refused", facts_sharing_it: 2 }]);
  assert.throws(() => composeRecords(twice), /derive one id and overwrite each other/,
    "silently writing one record for two facts is the failure this refusal exists to prevent");
});

await test("--compose refuses by name while B-T2.2's writer is absent, and takes it when it is there", async () => {
  // The first half of this test asserted the refusal until 2026-09-20. B-T2.2
  // landed `bot/lib/decisions.mjs`, so `resolveWriter({})` now resolves, and
  // the title's second clause — "and takes it when it is there" — is the half
  // that still has work to do. The refusal branch is kept by passing a root
  // where the module genuinely is not, so the sentence it prints is still
  // pinned for whoever meets it in a checkout without the module.
  await assert.rejects(
    () => resolveWriter({ root: "/nowhere", load: async () => { throw new Error("ENOENT"); } }),
    /decision-record writer/,
    "there is no second composer here, and the refusal says whose the first one is",
  );
  const writer = await resolveWriter({
    root: "/nowhere",
    load: async () => ({ writeDecisionRecord: () => ({ path: "log/decisions/2026/08/abc.json" }) }),
  }).catch((e) => e);
  assert.ok(writer instanceof Error, "a root with no decisions.mjs still refuses, before the loader is asked");
});


let failures = 0;
let passed = 0;
async function test(name, fn) {
  try {
    await fn();
    passed++;
    console.log(`  ok    ${name}`);
  } catch (e) {
    failures++;
    console.error(`  FAIL  ${name}\n        ${String(e.message).split("\n").join("\n        ")}`);
  }
}

const BOT = { login: BOT_LOGINS[0], type: "Bot" };

/**
 * A whole bot comment, rendered by the two modules that render the real ones.
 *
 * `bot/decide.mjs:143` joins the halves with a single newline; anything else
 * here would be testing a document this registry never posts.
 */
function botComment({ repo, tag, id, version, outcome, errors = [], reviews = [], approvedBy = null }) {
  const items = [
    ...errors.map((code) => ({ level: "error", code, where: "release", message: "the check that failed" })),
    ...reviews.map((code) => ({ level: "review", code, where: "version", message: "a decision for a person" })),
    { level: "pass", code: "E_DIGEST_MISMATCH", where: "asset", message: "sha256 abc…, 100 bytes, noarch" },
  ];
  const f = { items, errors: errors.map((code) => ({ code })), reviews: reviews.map((code) => ({ code })) };
  const derived = { plugin: { id }, version: { version } };
  const checks = renderComment(f, derived, { repo, tag });
  const decision = {
    outcome,
    repo,
    tag,
    fingerprint: "be6bc6b4f4139c5d",
    artifact_digests: ["sha256:abc"],
    publish_after: "2026-08-20T07:19:05Z",
    sla_deadline: "2026-09-15T10:37:55Z",
    queue_entry: { delay_hours: 24 },
    reasons: reviews.map((code) => ({ level: "review", code, message: "a decision for a person" })),
    // The approver, whom `renderPolicySection` prints as `**@login**` and whom
    // PRIV-10 says this export must turn into `system`. Planted so the needle
    // scan below has something to find if anybody ever scrapes it back out.
    approved_by: approvedBy,
    approved_at: approvedBy ? "2026-09-12T16:56:15Z" : null,
  };
  return `${checks}\n${renderPolicySection(decision, derived)}`;
}

// ── the grammar, generated by the renderers it reads ────────────────────────

await test("the four publication verdicts, rendered by the modules that render the real ones", () => {
  const base = { repo: "owner/name", tag: "v0.1.0", id: "dice-roller", version: "0.1.2" };
  const read = (outcome, extra = {}) =>
    readDecision({ ...BOT, date: "2026-08-20T07:19:05Z", body: botComment({ ...base, outcome, ...extra }) });

  const refused = read("refuse", { errors: ["E_OWNERSHIP_UNPROVEN"] });
  assert.equal(refused.fact?.state, "refused", "`**Not published.**` is a refusal");
  assert.deepEqual(refused.fact.reasons, ["E_OWNERSHIP_UNPROVEN"], "and its codes come from the checks' table");

  assert.equal(read("publish").fact?.state, "approved", "`**Published.**` is an approval");
  assert.equal(read("delay").fact?.state, "approved",
    "and so is `**Publishing itself at …**` — the policy said yes; the queue entry is what makes it happen");

  const held = read("review", { reviews: ["R_FIRST_LISTING"] });
  assert.equal(held.fact, undefined, "a hold is not a decision");
  assert.equal(held.drop, "held", "and it is counted under its own name rather than as a parse failure");
});

await test("the repository and the tag come out of the marker, which the run composed", () => {
  const body = botComment({ repo: "KNICE-TECH/astra-chess", tag: "v0.1.17", id: "astra-chess", version: "0.1.17", outcome: "publish" });
  const { fact } = readDecision({ ...BOT, date: "2026-09-02T08:11:20Z", body });
  assert.equal(fact.repository, "KNICE-TECH/astra-chess");
  assert.equal(fact.tag, "v0.1.17");
  assert.equal(fact.plugin_id, "astra-chess");
  assert.equal(fact.version, "0.1.17");
  assert.equal(fact.date, "2026-09-02T08:11:20Z");
});

await test("a refusal names no plugin and no version, because the run never derived one", () => {
  // Rendered with an `id`/`version` the ingest half will not print on a
  // blocked report: the refusal's own headline carries neither, and inventing
  // them from the issue form is the thing the approval binding exists to stop.
  const body = botComment({ repo: "owner/name", tag: "v9.9.9", id: "ghost", version: "9.9.9", outcome: "refuse", errors: ["E_INPUT_TAG"] });
  const { fact } = readDecision({ ...BOT, date: "2026-08-12T00:20:18Z", body });
  assert.equal(fact.state, "refused");
  assert.equal(fact.plugin_id, null, "DEC-7 lets both be absent, and absent is the honest record");
  assert.equal(fact.version, null);
});

await test("a code bot/lib/codes.mjs does not declare is dropped and counted", () => {
  const body = botComment({ repo: "owner/name", tag: "v1", id: "x", version: "1.0.0", outcome: "refuse", errors: ["E_INPUT_REPO"] })
    .replace("| ❌ | `E_INPUT_REPO` |", "| ❌ | `E_RETIRED_IN_2025` |\n| ❌ | `E_INPUT_REPO` |");
  const r = readDecision({ ...BOT, date: "2026-08-12T00:20:18Z", body });
  assert.deepEqual(r.fact.reasons, ["E_INPUT_REPO"], "the declared code survives");
  assert.deepEqual(r.dropped, ["unknown_code"], "and the undeclared one is named, not carried as an opaque string");
});

